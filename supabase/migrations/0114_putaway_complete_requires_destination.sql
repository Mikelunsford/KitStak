-- ---------------------------------------------------------------------------
-- complete_putaway_task: same 3-arg signature, same in_progress -> done
-- transition and idempotent done early-return, but a NULL destination now
-- RAISES STATE_CONFLICT before the task is marked done (no more silent
-- zero-movement no-op). When a destination IS set it behaves exactly as 0109:
-- mark done, then emit the warehouse-flat transfer_out / transfer_in pair
-- (unit_cost_cents 0), letting the 0107 AFTER INSERT recompute shift the bin
-- stock while the warehouse total stays flat.
-- ---------------------------------------------------------------------------

create or replace function public.complete_putaway_task(
  p_putaway_task_id uuid,
  p_actor uuid,
  p_caller_org_id uuid
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_org_id uuid;
  v_status text;
  v_warehouse_id uuid;
  v_item_id uuid;
  v_quantity numeric(18,4);
  v_source_location_id uuid;
  v_actual_location_id uuid;
  v_lot_id uuid;
begin
  -- Row lock (for update): serialises concurrent completes on this task. The
  -- second transaction blocks here until the first commits, then re-reads
  -- status = 'done' below and returns idempotently, so the transfer_out /
  -- transfer_in pair is emitted exactly once. The
  -- stock_movements_putaway_task_uniq partial unique index is the DB-enforced
  -- backstop if a lock is ever bypassed.
  select org_id, status, warehouse_id, item_id, quantity,
         source_location_id, actual_location_id, lot_id
    into v_org_id, v_status, v_warehouse_id, v_item_id, v_quantity,
         v_source_location_id, v_actual_location_id, v_lot_id
    from public.putaway_tasks where id = p_putaway_task_id for update;

  if v_org_id is null or v_org_id <> p_caller_org_id then
    raise exception 'NOT_FOUND: putaway task not found' using errcode = 'P0001';
  end if;

  if v_status = 'done' then
    return p_putaway_task_id; -- idempotent: a retried complete never double-emits
  end if;
  if v_status <> 'in_progress' then
    raise exception 'STATE_CONFLICT: putaway task not in in_progress state (was %)', v_status
      using errcode = 'P0001';
  end if;

  -- A complete REQUIRES a destination bin. Without one there is no bin to stow
  -- the stock in, so completing would emit zero movements and silently lose the
  -- move (the 0109 bug). Raise BEFORE marking the task done so the task stays
  -- in_progress and the operator can set the destination (set_putaway_destination)
  -- and complete again. STATE_CONFLICT, errcode P0001, mapped to 409 by the Edge.
  if v_actual_location_id is null then
    raise exception 'STATE_CONFLICT: putaway requires a destination bin'
      using errcode = 'P0001';
  end if;

  update public.putaway_tasks
     set status = 'done', completed_at = now(), updated_by = p_actor
   where id = p_putaway_task_id;

  -- Warehouse-flat internal move. The 0107 AFTER INSERT trigger fires the
  -- warehouse + bin recomputes per row; do not call recompute directly.
  -- unit_cost_cents = 0: a relocation, not a revaluation. transfer_out at the
  -- source dock and transfer_in at the destination bin net to zero at the
  -- warehouse grain (0030 signed-CASE), so the warehouse total stays flat while
  -- the bin grain shifts the quantity. When v_source_location_id is NULL the
  -- transfer_out is a no-bin reduction (warehouse -qty, no bin row), still
  -- warehouse-flat against the transfer_in.
  insert into public.stock_movements (
    org_id, warehouse_id, item_id,
    location_id, lot_id,
    movement_type, quantity, unit_cost_cents,
    source_entity_type, source_entity_id,
    occurred_at, created_by
  ) values (
    v_org_id, v_warehouse_id, v_item_id,
    v_source_location_id, v_lot_id,
    'transfer_out', v_quantity, 0,
    'putaway_task', p_putaway_task_id,
    now(), p_actor
  ), (
    v_org_id, v_warehouse_id, v_item_id,
    v_actual_location_id, v_lot_id,
    'transfer_in', v_quantity, 0,
    'putaway_task', p_putaway_task_id,
    now(), p_actor
  );

  return p_putaway_task_id;
end;
$$;

revoke execute on function public.complete_putaway_task(uuid, uuid, uuid) from public, anon;
grant execute on function public.complete_putaway_task(uuid, uuid, uuid) to service_role;
-- Preserve the 0111 hardening: action RPCs are called only via the Edge
-- service_role client, so authenticated must NOT retain EXECUTE. The CREATE OR
-- REPLACE above re-runs the 0109 grants whose body defaults would otherwise
-- restore the authenticated grant; re-revoke it here.
revoke execute on function public.complete_putaway_task(uuid, uuid, uuid) from authenticated;

