-- ---------------------------------------------------------------------------
-- set_putaway_destination: set (or correct) the destination bin on a still-open
-- task. 4-arg cross-tenant pattern: reads the task's org from the row, NOT_FOUND
-- on a cross-tenant or missing task (never 403). Allowed only while the task is
-- pending ('suggested') or in_progress; a done / cancelled task STATE_CONFLICTs
-- (its destination is frozen). Sets actual_location_id and updated_by; the 0109
-- updated_at trigger stamps updated_at. Status-only-adjacent: this is a plain
-- field UPDATE, NOT a status transition. The Edge layer validates the bin lives
-- in the task's warehouse before calling this (assertLocationInWarehouse).
-- ---------------------------------------------------------------------------

create or replace function public.set_putaway_destination(
  p_putaway_task_id uuid,
  p_actual_location_id uuid,
  p_actor uuid,
  p_caller_org_id uuid
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_org_id uuid;
  v_status text;
begin
  -- Row lock (for update): serialises a concurrent set / complete on this task.
  select org_id, status into v_org_id, v_status
    from public.putaway_tasks where id = p_putaway_task_id for update;

  if v_org_id is null or v_org_id <> p_caller_org_id then
    raise exception 'NOT_FOUND: putaway task not found' using errcode = 'P0001';
  end if;

  -- Only a still-open task can take a destination. A done task has already
  -- posted its movements against a frozen destination; a cancelled task never
  -- will. status 'suggested' is the 0109 'pending' equivalent (the FSM names the
  -- initial state 'suggested').
  if v_status not in ('suggested', 'in_progress') then
    raise exception 'STATE_CONFLICT: putaway destination cannot be set (was %)', v_status
      using errcode = 'P0001';
  end if;

  update public.putaway_tasks
     set actual_location_id = p_actual_location_id, updated_by = p_actor
   where id = p_putaway_task_id;

  return p_putaway_task_id;
end;
$$;

revoke execute on function public.set_putaway_destination(uuid, uuid, uuid, uuid) from public, anon;
grant execute on function public.set_putaway_destination(uuid, uuid, uuid, uuid) to service_role;
-- Action RPC, called only via the Edge service_role client: authenticated never
-- gets EXECUTE (the 0111 posture for action RPCs).
revoke execute on function public.set_putaway_destination(uuid, uuid, uuid, uuid) from authenticated;

comment on function public.set_putaway_destination(uuid, uuid, uuid, uuid) is
  'Sets (or corrects) the destination bin (actual_location_id) on a still-open putaway task (Wave 13 / R-W13-WMS-01). 4-arg cross-tenant guard (NOT_FOUND). Allowed only while status is suggested or in_progress; a done or cancelled task STATE_CONFLICTs. Plain field UPDATE, not a status transition. Pairs with the new complete_putaway_task rule that a NULL destination raises STATE_CONFLICT. The Edge validates the bin lives in the task warehouse before calling.';
