-- Migration: 0113_function_search_path_and_anon_execute_hardening.sql
-- Wave: 13
-- Phase: A. Function hardening. Two Supabase security-advisor findings are
--   closed here against schema public:
--   (1) function_search_path_mutable (37 functions): every function whose
--       search_path is not pinned is exposed to search-path-injection. A role
--       that can create objects in a schema earlier on the resolution path
--       could shadow an unqualified name the function body references and run
--       attacker-controlled code under the function. The 37 are the 36
--       trg_*_set_updated_at trigger functions plus the kitstak_audit_canonical
--       JSON-normaliser helper. We pin each to `SET search_path = public` via
--       ALTER FUNCTION. No body is rewritten and no behaviour changes; this is
--       a resolution-context change only. (The SECURITY DEFINER action RPCs and
--       the SECURITY DEFINER trigger functions already pin search_path and are
--       not in scope.)
--   (2) anon_security_definer_function_executable (11 functions): SECURITY
--       DEFINER functions in the exposed API schema are reachable by the anon
--       role. Ten are SECURITY DEFINER trigger functions (Postgres rejects a
--       direct RPC call to a trigger function, so the practical surface is the
--       revoke being defence in depth) and the eleventh, resolve_org_by_host,
--       is the host-to-org resolver. resolve_org_by_host is invoked from the
--       Edge layer via admin() (service_role); the public pre-auth host-resolve
--       path runs through the tenants-api Edge Function (verify_jwt = false),
--       not through a direct anon /rest/v1/rpc call. Revoking EXECUTE from
--       public and anon on all 11 closes the finding without affecting the Edge
--       call path. anon inherits the default PUBLIC execute grant, so PUBLIC must
--       be revoked too, not anon alone; resolve_org_by_host keeps its explicit
--       authenticated and service_role grants.
--   service_role and authenticated grants are left untouched: every legitimate
--   caller is service_role (Edge admin()) or the Postgres trigger machinery,
--   neither of which is the anon role. This mirrors the revoke pattern in
--   migration 0111.
-- Closes: R-W13-SEC-02
-- Date: 2026-06-15
--
-- DOWN MIGRATION (operator-only):
--   search_path pin reversal (per function below):
--     alter function public.<fn>(<sig>) reset search_path;
--   anon EXECUTE re-grant reversal (per function below):
--     grant execute on function public.<fn>(<sig>) to public;
--   No data is touched; both changes are configuration/privilege-only and are
--   fully reversible. Do NOT edit this file after apply; write a new forward
--   migration if a reset or re-grant is ever needed.
