--   - RLS is unaffected: the RLS-context helpers (current_org_id,
--     current_user_role) are not in either list and keep their grants.
--   - Edge is unaffected: resolve_org_by_host is called via admin()
--     (service_role), which retains EXECUTE. The trigger functions fire from
--     the Postgres trigger machinery, not from a role grant.
--   - Idempotent: ALTER FUNCTION ... SET search_path is a CREATE-OR-REPLACE
--     style attribute write (re-applying sets the same value), and REVOKE is
--     naturally idempotent (revoking an absent grant is a no-op and does not
--     error). Safe to re-apply.
--   - All 37 + 11 targets were enumerated from pg_proc against the live schema
--     (exact argument signatures below) so ALTER/REVOKE resolve unambiguously.
